CREATE TABLE schedules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id INTEGER NOT NULL CONSTRAINT fk_schedules_stores REFERENCES stores(id),
    week_day INTEGER NOT NULL CONSTRAINT ck_schedules_week_day CHECK (week_day BETWEEN 1 AND 7),
    opening_time TIME NOT NULL,
    closing_time TIME NOT NULL CONSTRAINT ck_schedules_closing_after_opening CHECK (closing_time > opening_time),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);

CREATE INDEX idx_schedules_store_id_week_day ON schedules(store_id, week_day);
