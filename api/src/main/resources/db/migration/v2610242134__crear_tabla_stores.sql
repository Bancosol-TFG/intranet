CREATE TABLE stores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chain_id INTEGER NOT NULL CONSTRAINT fk_stores_chains REFERENCES chains(id),
    name VARCHAR NOT NULL,
    address VARCHAR NOT NULL,
    checkout_shelfs INTEGER NOT NULL CONSTRAINT ck_stores_checkout_shelfs_non_negative CHECK (checkout_shelfs >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX uq_stores_name ON stores(name) WHERE deleted_at IS NULL;
CREATE INDEX idx_stores_chain_id ON stores(chain_id);
