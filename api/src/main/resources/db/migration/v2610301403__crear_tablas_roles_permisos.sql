CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT pk_roles PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_roles_name ON roles(name) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS permissions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT pk_permissions PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_permissions_name ON permissions(name)
    WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS role_permissions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    role_id INTEGER NOT NULL,
    permission_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT pk_role_permissions PRIMARY KEY (id),
    CONSTRAINT fk_role_permissions_roles FOREIGN KEY (role_id) REFERENCES roles(id),
    CONSTRAINT fk_role_permissions_permissions FOREIGN KEY (permission_id) REFERENCES permissions(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_role_permissions_role_id_permission_id
    ON role_permissions(role_id, permission_id)
    WHERE deleted_at IS NULL;
