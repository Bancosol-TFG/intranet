CREATE TABLE schedule_exceptions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id INTEGER NOT NULL,
    date DATE NOT NULL,
    opening_time TIME,
    closing_time TIME,
    closed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT fk_schedule_exceptions_stores FOREIGN KEY (store_id) REFERENCES stores(id),
    CONSTRAINT ck_schedule_exceptions_closed_or_slot CHECK (
        (closed AND opening_time IS NULL AND closing_time IS NULL)
        OR (NOT closed AND opening_time IS NOT NULL AND closing_time IS NOT NULL AND closing_time > opening_time)
    )
);

CREATE INDEX idx_schedule_exceptions_store_id_date ON schedule_exceptions (store_id, date);
