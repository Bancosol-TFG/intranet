CREATE TABLE campaigns (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_type_id INTEGER NOT NULL,
    name VARCHAR NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT fk_campaigns_campaign_types FOREIGN KEY (campaign_type_id) REFERENCES campaign_types (id),
    CONSTRAINT ck_campaigns_dates CHECK (start_date <= end_date)
);

CREATE INDEX idx_campaigns_campaign_type_id ON campaigns (campaign_type_id);
