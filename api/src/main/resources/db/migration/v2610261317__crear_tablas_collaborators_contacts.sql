CREATE TABLE collaborators (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 address TEXT NOT NULL,
 locality_id INTEGER NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 deleted_at TIMESTAMPTZ,
 CONSTRAINT fk_collaborators_localities FOREIGN KEY (locality_id) REFERENCES localities(id)
);
CREATE INDEX idx_collaborators_locality_id ON collaborators(locality_id) WHERE deleted_at IS NULL;
CREATE TABLE contacts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 email TEXT,
 phone_number TEXT,
 collaborator_id INTEGER NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 deleted_at TIMESTAMPTZ,
 CONSTRAINT fk_contacts_collaborators FOREIGN KEY (collaborator_id) REFERENCES collaborators(id)
);
CREATE INDEX idx_contacts_collaborator_id ON contacts(collaborator_id) WHERE deleted_at IS NULL;
